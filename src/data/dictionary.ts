// Helper to find a word in dictionary by exact or normalized English text
export function lookupDictionaryWord(text: string): VocabularyWord | undefined {
  if (!text) return undefined;
  const clean = text.toLowerCase().replace(/[^a-z]/g, '');
  return VOCABULARY_LIST.find((item) => {
    const itemClean = item.word.toLowerCase().replace(/[^a-z]/g, '');
    return itemClean === clean || item.id === clean;
  });
}
